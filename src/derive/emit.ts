import { WEBMCP_PIN } from '../spec-pin.ts'
import type { DerivedTool } from '../types.ts'

export function emitSnippet(siteId: string, tools: DerivedTool[]): string {
  const registrations = tools
    .map((tool) => {
      return `  await modelContext.registerTool({
    name: ${JSON.stringify(tool.name)},
    title: ${JSON.stringify(tool.title)},
    description: ${JSON.stringify(tool.description)},
    inputSchema: ${JSON.stringify(tool.inputSchema, null, 4).replace(/\n/g, '\n    ')},
    annotations: ${JSON.stringify(tool.annotations)},
    async execute(input, options) {
      return executeRecordedForm(${JSON.stringify(tool.plan)}, input as Record<string, unknown>, options?.signal)
    },
  })`
    })
    .join('\n')

  return `// Generated by webmcp-retrofit for the ${siteId} demo. Do not edit by hand.
// Copyright 2026 WebMCP-Retrofit contributors. Apache-2.0.
//
// Pinned WebMCP surface: ${WEBMCP_PIN.api}
// Spec: ${WEBMCP_PIN.specRepo}/commit/${WEBMCP_PIN.specCommit}
// Polyfill consulted: ${WEBMCP_PIN.polyfillPackage}@${WEBMCP_PIN.polyfillVersion}
//   upstream ${WEBMCP_PIN.polyfillUpstreamRevision}
//
// ${WEBMCP_PIN.deprecatedAliasNotEmitted} is the deprecated pre-document.modelContext
// name. This snippet does not assign it. ${WEBMCP_PIN.removedMethodsNotEmitted.join(' / ')}
// were removed from the spec and are not emitted.

import {
  executeRecordedForm,
  installDocumentModelContext,
  installTransportTap,
} from '../../src/runtime/browser.ts'
import type { ModelContext } from '../../src/polyfill/model-context.ts'

export const WEBMCP_PIN = ${JSON.stringify(WEBMCP_PIN, null, 2)} as const

export const siteId = ${JSON.stringify(siteId)}

declare const __RETROFIT_AUTO_INSTALL__: boolean | undefined

export async function registerRetrofitTools(modelContext: ModelContext): Promise<void> {
${registrations}
}

async function installAndRegisterTools(): Promise<void> {
  installTransportTap()
  const modelContext = installDocumentModelContext(document)
  await registerRetrofitTools(modelContext)
}

if (typeof __RETROFIT_AUTO_INSTALL__ !== 'undefined' && __RETROFIT_AUTO_INSTALL__) {
  window.__retrofitReady = installAndRegisterTools()
}
`
}

export function emitContractTest(siteId: string, toolNames: string[]): string {
  return `// Generated by webmcp-retrofit for the ${siteId} demo. Do not edit by hand.
// Copyright 2026 WebMCP-Retrofit contributors. Apache-2.0.
import assert from 'node:assert/strict'
import { test } from 'node:test'
import { runGeneratedContract } from '../../src/contract/run.ts'

test(${JSON.stringify(`${siteId} generated WebMCP contract`)}, async () => {
  const report = await runGeneratedContract(new URL('./contract.json', import.meta.url))
  assert.deepEqual(report.toolNames, ${JSON.stringify(toolNames)})
  assert.equal(report.failed, 0, report.checks.filter((check) => !check.pass).map((check) => check.id + ': ' + check.detail).join('\\n'))
})
`
}

export function contractDocument(siteId: string, tools: DerivedTool[]) {
  return {
    siteId,
    specPin: WEBMCP_PIN,
    tools,
  }
}
